# \brief wav2h - turn a WAV file into a C++ header with a byte array, for sid::play_wav() (sid/src/player.h)
#        The whole file goes into the array, so the header is its own description: sample rate, bits and
#        channels are read from it at run time. sid plays uncompressed PCM, 8 or 16 bit, mono or stereo; other
#        files are refused here. Chunks other than 'fmt ' and 'data' (tags, cue points) are left out.
#
#          python wav2h.py clip.wav clip.h [--name clip]
# ------------------------------------------------------------------------------

import argparse
import os
import struct
import sys


def read_wav(data):
    """\\return (fmt chunk content, data chunk content) of a PCM WAV file, raises ValueError otherwise"""
    if len(data) < 12 or data[0:4] != b'RIFF' or data[8:12] != b'WAVE':
        raise ValueError('not a RIFF / WAVE file')
    fmt = None
    pos = 12
    while len(data) - pos >= 8:
        ident = data[pos:pos + 4]
        length = struct.unpack_from('<I', data, pos + 4)[0]
        content = data[pos + 8:pos + 8 + length]
        if ident == b'fmt ':
            fmt = content
        elif ident == b'data':
            if fmt is None:
                raise ValueError("'data' before 'fmt '")
            return fmt, content
        pos += 8 + length + (length & 1)
    raise ValueError('no samples')


def convert(data, name, source):
    """\\return the text of the header"""
    fmt, samples = read_wav(data)
    if len(fmt) < 16:
        raise ValueError("'fmt ' too short")
    coding, channels, rate, _, align, bits = struct.unpack_from('<HHIIHH', fmt, 0)
    if coding == 0xFFFE and len(fmt) >= 40:
        coding = struct.unpack_from('<H', fmt, 24)[0]
    if coding != 1 or channels not in (1, 2) or bits not in (8, 16) or align != channels * bits // 8:
        raise ValueError('only uncompressed PCM, 8 or 16 bit, mono or stereo (this file: coding %d, %d bit, %d channels)'
                         % (coding, bits, channels))
    samples = samples[:len(samples) - len(samples) % align]
    # a minimal file: 'fmt ' with the 16 PCM bytes, then 'data'
    fmt = struct.pack('<HHIIHH', 1, channels, rate, rate * align, align, bits)
    body = b'WAVE' + b'fmt ' + struct.pack('<I', len(fmt)) + fmt + b'data' + struct.pack('<I', len(samples)) + samples
    if len(samples) & 1:
        body += b'\x00'
    out = b'RIFF' + struct.pack('<I', len(body)) + body

    frames = len(samples) // align
    guard = '_' + name.upper() + '_H_'
    lines = [
        '// generated by tools/wav2h.py from %s - do not edit' % source,
        '// %d Hz, %d bit, %s, %d frames = %d ms, %d bytes' % (rate, bits, 'stereo' if channels == 2 else 'mono', frames,
                                                              frames * 1000 // rate, len(out)),
        '',
        '#ifndef %s' % guard,
        '#define %s' % guard,
        '',
        '#include <cstdint>',
        '',
        '',
        '// a WAV file for sid::play_wav(out, %s, sizeof(%s))' % (name, name),
        'static const std::uint8_t %s[%dU] = {' % (name, len(out)),
    ]
    for i in range(0, len(out), 24):
        lines.append('  ' + ','.join('0x%02X' % b for b in out[i:i + 24]) + (',' if i + 24 < len(out) else ''))
    lines += ['};', '', '#endif  // %s' % guard, '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description='WAV file to C++ header for sid::play_wav()')
    parser.add_argument('wav', help='input: WAV file (PCM, 8 or 16 bit, mono or stereo)')
    parser.add_argument('header', help='output: header file')
    parser.add_argument('--name', help='name of the array (default: the name of the header file)')
    args = parser.parse_args()
    name = args.name or os.path.splitext(os.path.basename(args.header))[0]
    with open(args.wav, 'rb') as f:
        data = f.read()
    try:
        text = convert(data, name, os.path.basename(args.wav))
    except ValueError as e:
        sys.exit('wav2h: %s: %s' % (args.wav, e))
    with open(args.header, 'w', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
